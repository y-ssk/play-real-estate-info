package tilegrid

// area.go は「対応エリア（pref コード）→ タイル取得に使う bbox」の一元設定（ADR-0030 エリア段階）。
//
// なぜ pref ごとに明示 bbox を持てる形にするか：ADR-0030 は「bbox は admin_unit の ST_Extent、または
// 明示 bbox」を認める。東京都(13)の ST_Extent は伊豆・小笠原の島嶼まで含み、矩形が経度 136〜154 度・
// 緯度 20〜36 度へ巨大化して z=13 でも十数万タイルに爆発する（島嶼の地価点は疎で、面塗り MVP の対象外）。
// よって東京は本土に限定した明示 bbox を持ち、他県は ST_Extent（DB 由来）をそのまま使う。
// 「島嶼を後続スライスで足す」判断はここ（設定）を編集するだけで済む＝コードを触らない（ADR-0030 継ぎ目）。

// PrefBBoxOverride は pref コード→明示 bbox（ST_Extent を使わず固定する県）。
//
// 東京(13)＝本土（23区＋多摩）に限定。矩形は緯度 35.5〜35.9N・経度 138.9〜139.95E で本土全域を
// margin 込みで覆う（fetch-xkt013.sh の東京本土範囲と同思想）。ここに無い pref は admin_unit の
// ST_Extent（島嶼を含まない本土県はこれで十分＝埼玉/千葉/神奈川）を使う。
var PrefBBoxOverride = map[string]BBox{
	"13": {MinLon: 138.90, MinLat: 35.50, MaxLon: 139.95, MaxLat: 35.90},
}

// XPT002TileZoom は地価(XPT002)取得に使う XYZ ズーム。
//
// XPT002 の許容は z=13〜15。最小の z=13 を採る：地価の標準地/基準地は疎な点（1都3県で数千点規模）で、
// z が上がるほどタイル枚数が 4 倍に増え取得時間・API 負荷が跳ねる。点が疎ゆえ低ズームの粗い格子で
// 十分に全点を拾える（1タイルに複数点が入っても GeoJSON は全点返す）。z=13 でも 1都3県で ~2000 枚
// （東京は本土 bbox で数百枚）＝レート制御込みで一度きりのバッチとして現実的。
const XPT002TileZoom = 13
